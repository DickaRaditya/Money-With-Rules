const fs = require("node:fs");
const path = require("node:path");
const target = path.resolve(__dirname, "../../../apps/web/src/generated");
fs.mkdirSync(target, { recursive: true });
for (const name of ["MockToken", "MerchantRegistry", "MoneyWithRulesVault"]) {
  const { abi } = require(`../artifacts/contracts/${name}.sol/${name}.json`);
  fs.writeFileSync(
    path.join(target, `${name}.ts`),
    `// Generated by npm run compile. Do not hand-edit.\nexport const ${name}Abi = ${JSON.stringify(abi, null, 2)} as const;\n`,
  );
}
